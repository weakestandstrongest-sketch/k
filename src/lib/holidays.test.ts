import { describe, expect, it } from 'vitest';
import { holidayName, holidaysOf } from './holidays';

describe('日本の祝日', () => {
  it('2026 年の祝日（シルバーウィークと振替休日を含む）', () => {
    const list = [...holidaysOf(2026).entries()].sort(([a], [b]) => a.localeCompare(b));
    expect(list).toEqual([
      ['2026-01-01', '元日'],
      ['2026-01-12', '成人の日'],
      ['2026-02-11', '建国記念の日'],
      ['2026-02-23', '天皇誕生日'],
      ['2026-03-20', '春分の日'],
      ['2026-04-29', '昭和の日'],
      ['2026-05-03', '憲法記念日'],
      ['2026-05-04', 'みどりの日'],
      ['2026-05-05', 'こどもの日'],
      ['2026-05-06', '振替休日'],
      ['2026-07-20', '海の日'],
      ['2026-08-11', '山の日'],
      ['2026-09-21', '敬老の日'],
      ['2026-09-22', '国民の休日'],
      ['2026-09-23', '秋分の日'],
      ['2026-10-12', 'スポーツの日'],
      ['2026-11-03', '文化の日'],
      ['2026-11-23', '勤労感謝の日'],
    ]);
  });

  it('振替休日・特例の年', () => {
    expect(holidayName('2025-02-24')).toBe('振替休日'); // 2/23 が日曜
    expect(holidayName('2027-03-22')).toBe('振替休日'); // 春分 3/21 が日曜
    expect(holidayName('2021-07-23')).toBe('スポーツの日');
    expect(holidayName('2021-10-11')).toBeNull();
    expect(holidayName('2026-10-21')).toBeNull();
  });
});
